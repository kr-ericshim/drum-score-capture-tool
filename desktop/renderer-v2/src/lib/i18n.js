function normalizeLocale(locale = "") {
  const normalized = String(locale || "").trim().toLowerCase();
  if (SUPPORTED_LOCALES.includes(normalized)) {
    return normalized;
  }
  return normalized.startsWith("ko") ? "ko" : "en";
}

export function detectInitialLocale({ storageValue, navigatorLanguage } = {}) {
  const savedLocale = storageValue ?? globalThis?.localStorage?.getItem?.(LOCALE_STORAGE_KEY);
  if (savedLocale) {
    return normalizeLocale(savedLocale);
  }
  const browserLocale = navigatorLanguage ?? globalThis?.navigator?.language;
  return normalizeLocale(browserLocale);
}

export function persistLocale(locale, storage = globalThis?.localStorage) {
  const nextLocale = normalizeLocale(locale);
  storage?.setItem?.(LOCALE_STORAGE_KEY, nextLocale);
  return nextLocale;
}

export function t(key, { locale = "en", replacements = {} } = {}) {
  const table = translations[normalizeLocale(locale)] || translations.en;
  const fallback = translations.en[key] || key;
  const template = table[key] || fallback;

  return Object.entries(replacements).reduce((text, [name, value]) => {
    return text.replaceAll(`{${name}}`, String(value));
  }, template);
}

const HANGUL = /[\u3131-\u318e\uac00-\ud7a3]/;

/**
 * Backend notes are written once in both languages as "한국어 / English". Show only the
 * part for the UI language; text in one language comes back unchanged.
 */
export function pickLocalizedText(text, locale = "en") {
  const value = String(text ?? "").trim();
  if (!value.includes(" / ")) return value;
  const parts = value.split(" / ");
  // the English part starts after the last part that contains Hangul
  for (let cut = 1; cut < parts.length; cut += 1) {
    const korean = parts.slice(0, cut).join(" / ").trim();
    const english = parts.slice(cut).join(" / ").trim();
    if (korean && english && HANGUL.test(korean) && !HANGUL.test(english)) {
      return normalizeLocale(locale) === "ko" ? korean : english;
    }
  }
  return value;
}

/** Readable text from anything thrown or returned as an error detail (never "[object Object]"). */
export function errorDetailText(value, depth = 0) {
  if (value === null || value === undefined) return "";
  if (typeof value === "string") return value.trim();
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  if (depth > 3 || typeof value !== "object") return "";
  if (Array.isArray(value)) {
    return value.map((item) => errorDetailText(item, depth + 1)).filter(Boolean).join("; ");
  }
  for (const key of ["message", "detail", "msg", "reason", "error"]) {
    const text = errorDetailText(value[key], depth + 1);
    if (text) return text;
  }
  const name = typeof value.name === "string" ? value.name.trim() : "";
  return name && name !== "Error" ? name : "";
}

/** A user-facing message for an error, in the UI language. */
export function describeError(error, locale = "en") {
  const detail = errorDetailText(error);
  if (/^(REQUEST_TIMEOUT|TimeoutError)\b/.test(detail) || error?.name === "TimeoutError") return t("error.requestTimeout", { locale });
  if (/^REQUEST_FAILED\b/.test(detail)) return t("error.requestFailed", { locale });
  return pickLocalizedText(detail, locale) || t("error.unknown", { locale });
}

export { LOCALE_STORAGE_KEY, SUPPORTED_LOCALES };

/** Localize structured or plain reflow review reasons, retaining unknown diagnostic text. */
export function reflowReviewReasonText(reason, locale = "en") {
  const code = typeof reason === "string" ? reason : String(reason?.code || "");
  const key = `reflow.issue.${code}`;
  const translated = t(key, { locale });
  return translated !== key ? translated : pickLocalizedText(reason?.text || code, locale);
}
