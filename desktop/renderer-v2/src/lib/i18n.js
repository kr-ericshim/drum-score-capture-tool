function normalizeLocale(locale = "") {
  const normalized = String(locale || "").trim().toLowerCase();
  if (SUPPORTED_LOCALES.includes(normalized)) {
    return normalized;
  }
  return normalized.startsWith("ko") ? "ko" : "en";
}

export function detectInitialLocale({ storageValue, navigatorLanguage } = {}) {
  const savedLocale = storageValue ?? globalThis?.localStorage?.getItem?.(LOCALE_STORAGE_KEY);
  if (savedLocale) {
    return normalizeLocale(savedLocale);
  }
  const browserLocale = navigatorLanguage ?? globalThis?.navigator?.language;
  return normalizeLocale(browserLocale);
}

export function persistLocale(locale, storage = globalThis?.localStorage) {
  const nextLocale = normalizeLocale(locale);
  storage?.setItem?.(LOCALE_STORAGE_KEY, nextLocale);
  return nextLocale;
}

export function t(key, { locale = "en", replacements = {} } = {}) {
  const table = translations[normalizeLocale(locale)] || translations.en;
  const fallback = translations.en[key] || key;
  const template = table[key] || fallback;

  return Object.entries(replacements).reduce((text, [name, value]) => {
    return text.replaceAll(`{${name}}`, String(value));
  }, template);
}

export { LOCALE_STORAGE_KEY, SUPPORTED_LOCALES };
